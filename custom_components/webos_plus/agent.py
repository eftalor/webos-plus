"""Client for the optional root agent on a rooted TV.

The agent (tv/agent.sh in the repository) is the forced command of one SSH key
on the TV, so Home Assistant can only run the few commands it offers and never
gets a shell. The key is generated by this integration; the TV's host key is
pinned the first time the connection is tested.
"""

import asyncio
from contextlib import suppress
import json
from typing import Any

import asyncssh

from .const import LOGGER

AGENT_USER = "root"
AGENT_TIMEOUT = 20  # seconds for one command (stats takes about 1 s)
KEY_COMMENT = "webos_plus"


class AgentError(Exception):
    """The agent could not be reached or returned an error."""


class AgentAuthError(AgentError):
    """The TV refused the key (not installed in authorized_keys)."""


def generate_key() -> str:
    """Return a new ed25519 private key in OpenSSH format."""
    key = asyncssh.generate_private_key("ssh-ed25519", comment=KEY_COMMENT)
    return key.export_private_key().decode()


def public_key(private_key: str) -> str:
    """Return the one-line public key for a private key."""
    key = asyncssh.import_private_key(private_key)
    key.set_comment(KEY_COMMENT)
    return key.export_public_key().decode().strip()


async def async_fetch_host_key(host: str) -> str:
    """Return the TV's SSH host key (one line) for pinning."""
    try:
        async with asyncio.timeout(15):
            key = await asyncssh.get_server_host_key(host, 22, config=[])
    except (OSError, TimeoutError, asyncssh.Error) as err:
        raise AgentError(f"cannot read host key: {err}") from err
    if key is None:
        raise AgentError("the TV sent no host key")
    return key.export_public_key().decode().strip()


class TvAgent:
    """Run agent commands over one kept-open SSH connection."""

    def __init__(self, host: str, private_key: str, host_key: str) -> None:
        """Initialize."""
        self.host = host
        self._key = asyncssh.import_private_key(private_key)
        self._known_hosts = asyncssh.import_known_hosts(f"{host} {host_key}\n")
        self._conn: asyncssh.SSHClientConnection | None = None
        self._lock = asyncio.Lock()

    async def _async_connect(self) -> asyncssh.SSHClientConnection:
        return await asyncssh.connect(
            self.host,
            username=AGENT_USER,
            client_keys=[self._key],
            known_hosts=self._known_hosts,
            agent_path=None,
            config=[],
            connect_timeout=10,
            keepalive_interval=30,
        )

    async def async_run(self, command: str) -> dict[str, Any]:
        """Run one agent command and return its JSON reply."""
        async with self._lock:
            for attempt in (1, 2):
                try:
                    if self._conn is None:
                        self._conn = await self._async_connect()
                    async with asyncio.timeout(AGENT_TIMEOUT):
                        result = await self._conn.run(command, check=False)
                    break
                except asyncssh.PermissionDenied as err:
                    await self._async_close()
                    raise AgentAuthError(f"the TV refused the key: {err}") from err
                except (OSError, TimeoutError, asyncssh.Error) as err:
                    await self._async_close()
                    if attempt == 2:
                        raise AgentError(f"{command}: {err!r}") from err
                    LOGGER.debug("%s: agent connection lost, reconnecting: %r", self.host, err)

        out = str(result.stdout or "").strip()
        try:
            data = json.loads(out.splitlines()[-1]) if out else None
        except ValueError as err:
            raise AgentError(f"{command}: not JSON: {out[:200]!r}") from err
        if not isinstance(data, dict):
            raise AgentError(f"{command}: empty reply (exit {result.exit_status})")
        if "error" in data:
            raise AgentError(f"{command}: {data['error']}")
        return data

    async def _async_close(self) -> None:
        if self._conn is not None:
            self._conn.close()
            with suppress(Exception):
                await self._conn.wait_closed()
            self._conn = None

    async def async_close(self) -> None:
        """Close the connection."""
        async with self._lock:
            await self._async_close()
